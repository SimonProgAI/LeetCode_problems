public class Main{
    public static void main(String[] args){
        System.out.println("hello world");
        String firstName = "John";
        String lastName = "Matrix";
        String space = " ";
        String fullName = firstName + space + lastName;
        System.out.println(fullName);
        String studentName = "Joe joe";
        int studentId = 1234;
        int studentAge = 23;
        float studentFee = 45.45f;
        char studentGrade = 'B';

        System.out.println("Student Name: " + studentName);
        System.out.println("Student Age: " + studentAge);
        System.out.println("Student ID: " + studentId);
        System.out.println("Student Fee: " + studentFee);
        System.out.println("Student Grade: " + studentGrade);

        // PRIMITIVE DATA TYPES
        // byte - small whole numbers from -128 to 127
        // short - whole numbers from -32768 to 32767
        // int - whole numbers from minus 2 billion to 2 billion
        // long - big numbers, up to 9 quintillion
        // float - decimal numbers, up to 7 digits
        // double - decimal numbers up to 16 digits
        // boolean - true or false
        // char - a single character

        // NON-PRIMITIVE DATA TYPES
        // String - to store text
        // Arrays - used to store multiple values in a single variable
        // Classes - used as a "blueprint" for creating objects

    }
}